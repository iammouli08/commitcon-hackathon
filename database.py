"""Persistent user, Gmail-token, transaction, and review storage."""

import hashlib
import hmac
import os
import re
import secrets
import sqlite3
import time
import ipaddress
from pathlib import Path
from urllib.parse import quote, unquote, urlsplit, urlunsplit

import streamlit as st
from streamlit.errors import StreamlitSecretNotFoundError

DB_PATH = Path(__file__).parent / "users.db"


def _secret(name):
    try:
        return st.secrets.get(name)
    except StreamlitSecretNotFoundError:
        return None


def _database_url():
    database_url = os.getenv("DATABASE_URL") or _secret("DATABASE_URL")
    if not database_url:
        return None

    return _normalize_database_url(database_url)


def _normalize_database_url(database_url: str) -> str:
    match = re.match(r"^([A-Za-z][A-Za-z0-9+.-]*://)([^/?#]*)(.*)$", database_url)
    if not match:
        raise ValueError("DATABASE_URL must be a PostgreSQL URL with a hostname.")

    scheme, authority, suffix = match.groups()
    if "@" not in authority:
        raise ValueError("DATABASE_URL must include a username, password, and hostname.")
    user_info, host_port = authority.rsplit("@", 1)
    if ":" not in user_info:
        raise ValueError("DATABASE_URL must include a username and password.")
    username, password = user_info.split(":", 1)

    if host_port.startswith("["):
        closing_bracket = host_port.find("]")
        if closing_bracket == -1:
            raise ValueError("DATABASE_URL has an unmatched bracket in its hostname.")
        bracketed_host = host_port[1:closing_bracket]
        try:
            ipaddress.ip_address(bracketed_host)
        except ValueError:
            if not re.fullmatch(r"[A-Za-z0-9.-]+", bracketed_host):
                raise ValueError("DATABASE_URL has an invalid bracketed hostname.")
            host_port = bracketed_host + host_port[closing_bracket + 1:]

    encoded_user_info = f"{quote(unquote(username), safe='')}:{quote(unquote(password), safe='')}"
    database_url = f"{scheme}{encoded_user_info}@{host_port}{suffix}"
    parsed = urlsplit(database_url)
    if not parsed.username or parsed.password is None or not parsed.hostname:
        return database_url
    return urlunsplit(parsed)


def _is_postgres():
    return bool(_database_url())


def is_persistent():
    """Whether durable PostgreSQL storage is configured."""
    return _is_postgres()


def get_connection():
    database_url = _database_url()
    if database_url:
        import psycopg
        from psycopg.rows import dict_row

        return psycopg.connect(database_url, sslmode="require", row_factory=dict_row)
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def _execute(conn, sql, params=()):
    if _is_postgres():
        sql = sql.replace("?", "%s")
    return conn.execute(sql, params)


def hash_password(password: str, salt: str | None = None) -> tuple[str, str]:
    """Generates a PBKDF2-HMAC-SHA256 hash and salt for the password."""
    salt = salt or secrets.token_hex(16)
    pw_hash = hashlib.pbkdf2_hmac(
        "sha256", password.encode("utf-8"), salt.encode("utf-8"), iterations=100_000
    ).hex()
    return pw_hash, salt


def init_db():
    """Initialize local SQLite or configured PostgreSQL storage."""
    if _is_postgres():
        id_column = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        text_type = "TEXT"
        user_id_type = "BIGINT"
    else:
        id_column = "INTEGER PRIMARY KEY AUTOINCREMENT"
        text_type = "TEXT"
        user_id_type = "INTEGER"

    with get_connection() as conn:
        _execute(conn, f"""
            CREATE TABLE IF NOT EXISTS users (
                id {id_column},
                username {text_type} NOT NULL UNIQUE,
                password_hash {text_type} NOT NULL,
                salt {text_type} NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)
        _execute(conn, f"""
            CREATE TABLE IF NOT EXISTS gmail_tokens (
                user_id {user_id_type} PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
                encrypted_token {text_type} NOT NULL,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)
        _execute(conn, f"""
            CREATE TABLE IF NOT EXISTS transactions (
                user_id {user_id_type} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                transaction_id {text_type} NOT NULL,
                transaction_date {text_type},
                merchant {text_type} NOT NULL,
                amount REAL NOT NULL,
                direction {text_type} NOT NULL,
                category {text_type} NOT NULL,
                subject {text_type} NOT NULL,
                marked_normal INTEGER NOT NULL DEFAULT 0,
                PRIMARY KEY (user_id, transaction_id)
            )
        """)
        _execute(conn, f"""
            CREATE TABLE IF NOT EXISTS gmail_oauth_states (
                state_hash {text_type} PRIMARY KEY,
                user_id {user_id_type} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                expires_at BIGINT NOT NULL,
                encrypted_verifier {text_type}
            )
        """)
        if _is_postgres():
            _execute(
                conn,
                "ALTER TABLE gmail_oauth_states ADD COLUMN IF NOT EXISTS encrypted_verifier TEXT",
            )
        else:
            oauth_state_columns = {
                row["name"] for row in _execute(conn, "PRAGMA table_info(gmail_oauth_states)").fetchall()
            }
            if "encrypted_verifier" not in oauth_state_columns:
                _execute(
                    conn,
                    "ALTER TABLE gmail_oauth_states ADD COLUMN encrypted_verifier TEXT",
                )
def _normalized_username(username: str) -> str:
    return username.strip().lower() if username else ""


def verify_user(username: str, password: str) -> bool:
    if not username or not password:
        return False
    with get_connection() as conn:
        row = _execute(
            conn,
            "SELECT password_hash, salt FROM users WHERE username = ?",
            (_normalized_username(username),),
        ).fetchone()
    if not row:
        return False
    stored_hash = row["password_hash"]
    calc_hash, _ = hash_password(password, row["salt"])
    return hmac.compare_digest(stored_hash, calc_hash)


def create_user(username: str, password: str) -> tuple[bool, str]:
    clean_username = _normalized_username(username)
    if not clean_username:
        return False, "Username cannot be empty."
    if len(clean_username) < 3:
        return False, "Username must be at least 3 characters long."
    if len(clean_username) > 30:
        return False, "Username must not exceed 30 characters."
    if not re.match(r"^[A-Za-z0-9_.-]+$", clean_username):
        return False, "Username can only contain letters, numbers, hyphens, and underscores."
    if not password:
        return False, "Password cannot be empty."
    if len(password) < 10:
        return False, "Password must be at least 10 characters long."

    pw_hash, salt = hash_password(password)
    try:
        with get_connection() as conn:
            _execute(
                conn,
                "INSERT INTO users (username, password_hash, salt) VALUES (?, ?, ?)",
                (clean_username, pw_hash, salt),
            )
        return True, f"Account '{clean_username}' registered successfully! You can now log in."
    except (sqlite3.IntegrityError, _postgres_integrity_error()):
        return False, f"Username '{clean_username}' already exists."


def _postgres_integrity_error():
    try:
        import psycopg

        return psycopg.IntegrityError
    except ImportError:
        return type(None)


def _user_id(conn, username):
    row = _execute(
        conn, "SELECT id FROM users WHERE username = ?", (_normalized_username(username),)
    ).fetchone()
    return row["id"] if row else None


def has_gmail_token(username: str) -> bool:
    with get_connection() as conn:
        user_id = _user_id(conn, username)
        if user_id is None:
            return False
        return _execute(conn, "SELECT 1 FROM gmail_tokens WHERE user_id = ?", (user_id,)).fetchone() is not None


def save_gmail_token(username: str, encrypted_token: str):
    with get_connection() as conn:
        user_id = _user_id(conn, username)
        if user_id is None:
            raise ValueError("The signed-in account no longer exists.")
        _execute(
            conn,
            """
            INSERT INTO gmail_tokens (user_id, encrypted_token) VALUES (?, ?)
            ON CONFLICT(user_id) DO UPDATE SET
                encrypted_token = excluded.encrypted_token,
                updated_at = CURRENT_TIMESTAMP
            """,
            (user_id, encrypted_token),
        )


def get_gmail_token(username: str) -> str | None:
    with get_connection() as conn:
        user_id = _user_id(conn, username)
        if user_id is None:
            return None
        row = _execute(
            conn, "SELECT encrypted_token FROM gmail_tokens WHERE user_id = ?", (user_id,)
        ).fetchone()
        return row["encrypted_token"] if row else None


def save_gmail_oauth_state(
    username: str, state_hash: str, expires_at: int, encrypted_verifier: str
):
    with get_connection() as conn:
        user_id = _user_id(conn, username)
        if user_id is None:
            raise ValueError("The signed-in account no longer exists.")
        _execute(conn, "DELETE FROM gmail_oauth_states WHERE expires_at <= ?", (int(time.time()),))
        _execute(
            conn,
            """
            INSERT INTO gmail_oauth_states
                (state_hash, user_id, expires_at, encrypted_verifier)
            VALUES (?, ?, ?, ?)
            """,
            (state_hash, user_id, expires_at, encrypted_verifier),
        )


def consume_gmail_oauth_state(state_hash: str) -> tuple[str, str] | None:
    with get_connection() as conn:
        row = _execute(
            conn,
            """
            SELECT user_id, expires_at, encrypted_verifier
            FROM gmail_oauth_states WHERE state_hash = ?
            """,
            (state_hash,),
        ).fetchone()
        if not row:
            return None
        _execute(conn, "DELETE FROM gmail_oauth_states WHERE state_hash = ?", (state_hash,))
        if row["expires_at"] <= int(time.time()) or not row["encrypted_verifier"]:
            return None
        user = _execute(conn, "SELECT username FROM users WHERE id = ?", (row["user_id"],)).fetchone()
        return (user["username"], row["encrypted_verifier"]) if user else None


def delete_gmail_token(username: str):
    with get_connection() as conn:
        user_id = _user_id(conn, username)
        if user_id is not None:
            _execute(conn, "DELETE FROM gmail_tokens WHERE user_id = ?", (user_id,))


def save_transactions(username: str, records: list[dict]):
    with get_connection() as conn:
        user_id = _user_id(conn, username)
        if user_id is None:
            raise ValueError("The signed-in account no longer exists.")
        for record in records:
            _execute(
                conn,
                """
                INSERT INTO transactions
                    (user_id, transaction_id, transaction_date, merchant, amount,
                     direction, category, subject)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?)
                ON CONFLICT(user_id, transaction_id) DO NOTHING
                """,
                (
                    user_id,
                    str(record["id"]),
                    str(record["date"]) if record.get("date") is not None else None,
                    str(record["merchant"]),
                    float(record["amount"]),
                    str(record["direction"]),
                    str(record["category"]),
                    "",
                ),
            )


def get_transactions(username: str) -> list[dict]:
    with get_connection() as conn:
        user_id = _user_id(conn, username)
        if user_id is None:
            return []
        rows = _execute(
            conn,
            """
            SELECT transaction_id AS id, transaction_date AS date, merchant, amount,
                   direction, category, subject, marked_normal
            FROM transactions WHERE user_id = ? ORDER BY transaction_date DESC
            """,
            (user_id,),
        ).fetchall()
        return [dict(row) for row in rows]


def set_transaction_marked_normal(username: str, transaction_id: str, marked: bool):
    with get_connection() as conn:
        user_id = _user_id(conn, username)
        if user_id is None:
            raise ValueError("The signed-in account no longer exists.")
        _execute(
            conn,
            """
            UPDATE transactions SET marked_normal = ?
            WHERE user_id = ? AND transaction_id = ?
            """,
            (int(marked), user_id, transaction_id),
        )


def delete_transactions(username: str):
    with get_connection() as conn:
        user_id = _user_id(conn, username)
        if user_id is not None:
            _execute(conn, "DELETE FROM transactions WHERE user_id = ?", (user_id,))


def get_user_count() -> int:
    with get_connection() as conn:
        return _execute(conn, "SELECT COUNT(*) AS count FROM users").fetchone()["count"]
